// Builds the list of files `ultraner init` would write. Pure: no disk writes
// here, so the same output feeds --dry-run, the consent prompt and the tests.
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';

export const README_MARKER = '<!-- ultraner:init -->';
const GUIDE_SLUGS = { nextjs: 'nextjs', express: 'express', django: 'django', fastapi: 'fastapi', laravel: 'laravel', flutter: 'flutter' };

const posix = (p) => p.split(path.sep).join('/');

/** Where generated library code goes, relative to the project root. */
export function libDir(project) {
  if (project.framework === 'nextjs') return project.srcDir ? 'src/lib/ultraner' : 'lib/ultraner';
  return project.srcDir ? 'src/ultraner' : 'ultraner';
}

function rel(fromFile, toFile, ext) {
  let r = posix(path.relative(path.dirname(fromFile), toFile));
  if (!r.startsWith('.')) r = './' + r;
  return r + ext;
}

